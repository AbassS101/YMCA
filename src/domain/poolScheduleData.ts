function timeToMinutes(t: string): number {
  const [time, meridiem] = t.split(' ');
  const [hStr, mStr] = time.split(':');
  let h = parseInt(hStr, 10);
  const m = parseInt(mStr, 10);
  if (meridiem === 'PM' && h !== 12) h += 12;
  if (meridiem === 'AM' && h === 12) h = 0;
  return h * 60 + m;
}

function buildLaneAllocations(
  category: ActivityCategory,
  lapCount: number,
  recCount: number,
  progCount: number,
  progLabel: string
): LaneAllocation[] {
  const lanes: LaneAllocation[] = [];
  let current = 1;

  // Assign lap lanes first
  for (let i = 0; i < lapCount; i++) {
    let pace = 'Lap';
    if (i === 0) pace = 'Lap (Fast)';
    else if (i === 1) pace = 'Lap (Med-Fast)';
    else if (i === 2) pace = 'Lap (Medium)';
    else if (i === 3) pace = 'Lap (Slow)';
    else pace = 'Lap (Leisure)';
    lanes.push({
      laneNumber: current++,
      type: 'lap',
      label: pace,
    });
  }

  // Assign program lanes (water fitness, lessons, team, water polo, masters)
  for (let i = 0; i < progCount; i++) {
    lanes.push({
      laneNumber: current++,
      type:
        category === 'fitness'
          ? 'fitness'
          : category === 'lessons'
          ? 'lessons'
          : category === 'waterpolo'
          ? 'waterpolo'
          : 'team',
      label: progLabel,
    });
  }

  // Assign rec lanes
  for (let i = 0; i < recCount; i++) {
    lanes.push({
      laneNumber: current++,
      type: 'rec',
      label: 'Rec / Open Swim',
    });
  }

  // If closed or remaining
  while (lanes.length < 6) {
    lanes.push({
      laneNumber: current++,
      type: 'closed',
      label: 'Closed',
    });
  }

  return lanes;
}

